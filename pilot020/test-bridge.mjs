const e=(m,o=ORIGIN,s=source)=>({source:s,origin:o,data:JSON.stringify(m)});
const ping={method:scope+'::__ready',params:'ping'},good={method:scope+'::playbackStatusUpdate',params:{position:1,playbackState:'playing'}};
b.ping();assert.equal(sent[0][1],ORIGIN);
assert.equal(b.receive(e(ping,'https://evil.example')),false);
assert.equal(b.receive(e(ping,ORIGIN,other)),false);
assert.equal(b.receive(e({method:'old::__ready',params:'ping'})),false);
assert.equal(b.receive(e(good)),false);
assert.equal(b.receive(e(ping)),true);assert.equal(sent[1][0].params,'pong');
assert.equal(sent[2][0].method,scope+'::isReady');
assert.equal(b.receive(e({id:999,result:true})),false);
assert.equal(b.receive(e({id:1,result:'true'})),false);
assert.equal(b.receive(e({id:1,result:false})),true);assert.equal(b.ready,false);
b.query();assert.equal(b.receive(e({id:1,result:true})),false);
assert.equal(b.receive(e({id:2,result:true})),true);assert.equal(b.ready,true);
assert.deepEqual(events,[{kind:'ready'}]);
assert.equal(b.receive(e(good)),true);assert.equal(events[1].position,1);
assert.equal(b.receive(e({...good,params:{position:'1',playbackState:'playing'}})),false);
assert.equal(b.receive(e({...good,id:3})),false);
assert.equal(b.receive(e({...good,method:'wrong::playbackStatusUpdate'})),false);
assert.equal(b.receive(e(good,'https://evil.example')),false);
assert.equal(decode({source,origin:ORIGIN,data:'{'},source,scope),null);
assert.equal(decode({source,origin:ORIGIN,data:' '.repeat(4097)},source,scope),null);
