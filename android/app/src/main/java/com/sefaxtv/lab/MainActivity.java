package com.sefaxtv.lab;

import android.app.Activity;
import android.os.Bundle;
import android.net.Uri;
import android.webkit.WebView;
import android.webkit.WebViewClient;
import android.webkit.WebChromeClient;
import android.webkit.WebResourceRequest;
import android.webkit.WebResourceResponse;
import android.webkit.WebSettings;
import android.webkit.CookieManager;
import androidx.webkit.WebViewAssetLoader;
import androidx.webkit.WebViewCompat;
import androidx.webkit.WebViewFeature;
import androidx.webkit.JavaScriptReplyProxy;
import org.json.JSONObject;
import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.Collections;

/** Only local, owned LAB content. No third-party player or unrestricted bridge. */
public final class MainActivity extends Activity {
    private WebView web;
    private boolean foreground, installed, documentStarted;
    private final ProbeGate gate=new ProbeGate();
    private static final String PAGES="sedathut-sys.github.io";
    private static boolean localOrigin(Uri u) { return u!=null && "https".equals(u.getScheme()) && "appassets.androidplatform.net".equals(u.getHost()) && u.getPort()==-1 && u.getUserInfo()==null; }
    private static boolean pageOrigin(Uri u) { return u!=null && "https".equals(u.getScheme()) && PAGES.equals(u.getHost()) && u.getPort()==-1 && u.getUserInfo()==null; }
    private static boolean catalogRequest(Uri u) {return pageOrigin(u) && u.getQuery()==null && u.getPath()!=null && u.getPath().matches("/sefaxtv/catalog/(latest|v[1-9][0-9]{0,6})\\.json");}
    private static boolean localAsset(Uri u) { return localOrigin(u)&&u.getQuery()==null&&("/assets/index.html".equals(u.getPath())||"/assets/lab-player.html".equals(u.getPath())); }
    private static WebResourceResponse denied() { return new WebResourceResponse("text/plain","UTF-8",403,"Forbidden",Collections.emptyMap(),new ByteArrayInputStream(new byte[0])); }
    private String assetText(String name) throws Exception {try(InputStream in=getAssets().open(name);ByteArrayOutputStream out=new ByteArrayOutputStream()){byte[] buffer=new byte[4096];int n;while((n=in.read(buffer))!=-1)out.write(buffer,0,n);return new String(out.toByteArray(),StandardCharsets.UTF_8);}}
    @Override public void onCreate(Bundle saved) {
        super.onCreate(saved);
        web=new WebView(this);setContentView(web);
        WebSettings s=web.getSettings();s.setJavaScriptEnabled(true);s.setDomStorageEnabled(true);s.setAllowFileAccess(false);s.setAllowContentAccess(false);s.setMixedContentMode(WebSettings.MIXED_CONTENT_NEVER_ALLOW);s.setJavaScriptCanOpenWindowsAutomatically(false);s.setSupportMultipleWindows(false);s.setMediaPlaybackRequiresUserGesture(true);
        CookieManager.getInstance().setAcceptThirdPartyCookies(web,false);
        WebView.setWebContentsDebuggingEnabled(false);
        WebViewAssetLoader loader=new WebViewAssetLoader.Builder().addPathHandler("/assets/",new WebViewAssetLoader.AssetsPathHandler(this)).build();
        web.setWebChromeClient(new WebChromeClient());
        web.setWebViewClient(new WebViewClient(){
            @Override public WebResourceResponse shouldInterceptRequest(WebView view,WebResourceRequest r){
                Uri u=r.getUrl();if(!"GET".equals(r.getMethod()))return denied();
                if(localAsset(u)){WebResourceResponse response=loader.shouldInterceptRequest(u);return response!=null?response:denied();}
                if(catalogRequest(u))return null; // Browser performs ordinary HTTPS + CORS; no proxy or header override.
                return denied();
            }
            @Override public boolean shouldOverrideUrlLoading(WebView view,WebResourceRequest r){
                String url=r.getUrl().toString();
                if(r.isForMainFrame())return !ProbeGate.APP.equals(url);
                // Owned local fixture only. Opaque srcdoc is generated by our main HTML.
                return !(localAsset(r.getUrl()) && "/assets/lab-player.html".equals(r.getUrl().getPath()) || "about:srcdoc".equals(url)||"about:blank".equals(url));
            }
            @Override public void onPageStarted(WebView view,String url,android.graphics.Bitmap icon){gate.newDocument();documentStarted=ProbeGate.APP.equals(url);}
            @Override public void onPageFinished(WebView view,String url){if(foreground&&installed&&ProbeGate.APP.equals(url))view.evaluateJavascript("if(typeof hostSend==='function')hostSend({type:'host:hello'})",null);}
            @Override public boolean onRenderProcessGone(WebView view,android.webkit.RenderProcessGoneDetail detail) {gate.newDocument();documentStarted=false;installed=false;view.destroy();web=null;finish();return true;}
        });
        if(WebViewFeature.isFeatureSupported(WebViewFeature.WEB_MESSAGE_LISTENER)&&WebViewFeature.isFeatureSupported(WebViewFeature.DOCUMENT_START_SCRIPT)) {
            try {
                WebViewCompat.addWebMessageListener(web,"SefaXTVNative",Collections.singleton(ProbeGate.ORIGIN),(view,msg,origin,isMainFrame,reply)->{
                    if(view!=web||!foreground||!installed||!documentStarted||!isMainFrame||!localOrigin(origin)||!ProbeGate.APP.equals(view.getUrl()))return;
                    handle(msg.getData(),reply);
                });
                WebViewCompat.addDocumentStartJavaScript(web,assetText("observer.js"),Collections.singleton(ProbeGate.ORIGIN));
                installed=true;
            }catch(Exception ignored){installed=false;gate.newDocument();}
        }
    }
    private static long integer(JSONObject j,String name) throws Exception { Object x=j.get(name);if(!(x instanceof Number))throw new Exception("integer");double d=((Number)x).doubleValue();if(!Double.isFinite(d)||d!=Math.rint(d)||Math.abs(d)>9007199254740991d)throw new Exception("integer");return ((Number)x).longValue(); }
    private static double number(JSONObject j,String name) throws Exception {Object x=j.get(name);if(!(x instanceof Number))throw new Exception("number");double d=((Number)x).doubleValue();if(!Double.isFinite(d))throw new Exception("number");return d;}
    private static String string(JSONObject j,String name) throws Exception {Object x=j.get(name);if(!(x instanceof String))throw new Exception("string");return (String)x;}
    private void handle(String raw,JavaScriptReplyProxy reply){
        if(raw==null||raw.length()>4096)return;
        try {
            JSONObject j=new JSONObject(raw);if(!ProbeGate.PROTOCOL.equals(j.optString("protocol")))return;
            switch(j.optString("type")){
                case "host:hello":
                    gate.ready(true);reply.postMessage(new JSONObject().put("protocol",ProbeGate.PROTOCOL).put("type","host:ready").put("fixture",ProbeGate.FIXTURE).toString());break;
                case "probe:start": gate.start(integer(j,"seq"),string(j,"token"),string(j,"url"));break;
                case "probe:stop": gate.stop(integer(j,"seq"),string(j,"token"));break;
                case "probe:evidence":
                    JSONObject d=j.getJSONObject("evidence");
                    if(!ProbeGate.PROTOCOL.equals(d.optString("protocol"))||!"video:advanced".equals(d.optString("type")))return;
                    if(gate.proof(integer(d,"seq"),string(d,"token"),string(d,"url"),integer(d,"counter"),string(d,"method"),number(d,"mediaTime"),number(d,"delta"),integer(d,"frameDelta")))reply.postMessage(d.toString());break;
                default: break;
            }
        }catch(Exception ignored){ /* Malformed evidence never opens the cover. */ }
    }
    @Override protected void onResume(){super.onResume();foreground=true;if(web!=null){web.resumeTimers();web.onResume();if(!documentStarted)web.loadUrl(ProbeGate.APP);}}
    @Override protected void onPause(){foreground=false;gate.newDocument();documentStarted=false;if(web!=null){web.evaluateJavascript("if(typeof stop==='function')stop()",null);web.stopLoading();web.loadUrl("about:blank");web.onPause();web.pauseTimers();}super.onPause();}
    @Override protected void onDestroy(){foreground=false;gate.newDocument();if(web!=null){web.destroy();web=null;}super.onDestroy();}
}
